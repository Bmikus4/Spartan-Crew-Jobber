// Pull the tenant's profession list and write it in both the forms the tool needs:
//
//   data/professions.json          the raw list, read by test/professions.ts
//   app/lib/engine/professionList.ts   the same list as a TS module, so the engine
//                                      has a floor to resolve against with no
//                                      network and no database
//
// A generated module rather than a JSON import: the engine is consumed by Next, by
// tsx scripts and by the test runner, and a checked-in .ts file resolves the same
// way in all three with nothing to configure.
//
// It also writes the list into Neon when DATABASE_URL is set, which is the cache
// the engine actually reads at runtime.
//
// Run: node scripts/pull-professions.mjs
import fs from "node:fs";
import { loadEnv } from "./_env.mjs";

loadEnv();
const BASE = process.env.ONSINCH_BASE_URL;
const KEY = process.env.ONSINCH_API_KEY;
if (!BASE || !KEY) throw new Error("ONSINCH_BASE_URL / ONSINCH_API_KEY missing");

const res = await fetch(`${BASE}/professions?limit=100`, { headers: { Authorization: `apikey ${KEY}` } });
if (!res.ok) throw new Error(`GET /professions -> ${res.status}`);
const { data } = await res.json();
const rows = (data ?? []).map((p) => ({
  id: p.id,
  name: p.name,
  alias: p.alias ?? null,
  description: p.description ?? null,
  deleted: !!p.deleted,
}));
if (!rows.length) throw new Error("the tenant returned no professions — refusing to overwrite the list with nothing");

fs.writeFileSync("data/professions.json", JSON.stringify(rows, null, 1));

// The description field is dropped from the generated module: it holds paragraphs of
// tool lists and site rules that nothing in the resolver reads, and it would put a
// wall of prose into the engine's bundle for no benefit.
const slim = rows.map(({ id, name, alias, deleted }) => ({ id, name, alias, deleted }));
fs.writeFileSync(
  "app/lib/engine/professionList.ts",
  `// GENERATED by scripts/pull-professions.mjs — do not edit by hand.\n` +
    `// The tenant's profession list, committed so the engine can resolve all of them\n` +
    `// with no network and no database. Descriptions are dropped; nothing reads them.\n` +
    `import type { ProfessionRec } from "./professions";\n\n` +
    `export const PROFESSION_LIST: ProfessionRec[] = ${JSON.stringify(slim, null, 2)};\n`
);

console.log(`${rows.length} professions -> data/professions.json + app/lib/engine/professionList.ts`);

if ((process.env.DATABASE_URL || process.env.POSTGRES_URL || "").trim()) {
  const { storeProfessions } = await import("../app/lib/professionsDb.ts").catch(() => ({}));
  if (storeProfessions) console.log(`cached ${await storeProfessions(rows)} into Neon`);
}
